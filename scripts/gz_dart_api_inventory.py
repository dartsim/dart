#!/usr/bin/env python3
"""Inventory the DART C++ declarations referenced by Gazebo C++ sources.

This lexical, best-effort inventory records uses it can resolve. Unresolved
receivers retain conservative declaration candidates and an explicit count.
Known limitations:
- Namespace using-directives and aliases are treated file-wide.
- Source fields are keyed by name across owners.
- Function-local type aliases are not collected.
- Function-local classes and their virtual overrides are not collected.
- Preprocessor conditions are not generally evaluated.
- C++ template instantiation and overload resolution are not performed.
- Ignored in-tree build artifacts are scanned as Gazebo sources.
- Virtual destructor overrides are not recorded.
- Referenced macro parameters and replacement tokens are not recorded.
- Source-only inheritance chains beyond three hops can be missed.
- Public-to-protected declaration access changes are not recorded.
- Used free-function declarations and signatures are not recorded.
- Used type-alias target definitions are not recorded.
- Qualified member-function references without calls are not recorded.
- Dependent `receiver->template method<T>()` calls are not recognized.
- Base relationships of referenced DART types are not recorded.
- Trailing return types are not used to infer chained-call receivers.
- Availability of headers generated by CMake is not checked.

Operator syntax is associated with declarations for `->`, `[]` and `()` when
the receiver type is known. The Gazebo build and test lanes remain the
authoritative compatibility check.
Type lookup uses tracked scopes, from the innermost namespace or class,
including the class of an out-of-line member definition and the bases of
enclosing classes. A type alias is visible only in its file and in the files
that include it. Type aliases declared inside function bodies are not collected.

A construction lists the constructors that the type declares, including those
of its class template specializations, or, when it declares none, those of the
bases that its implicit constructor calls. A Gazebo class derived from a DART
class constructs that base, so its base clause counts as a construction.
Brace constructions of classes without declared constructors also retain public
non-static fields in declaration order as `brace_member_declarations`. This is
lexical field evidence; it does not establish C++ aggregate eligibility.

Preprocessor conditions are not evaluated, except that a literal `#if 0` or
`#if 1` drops the branches it rules out. Every other branch is scanned, so the
inventory also lists uses that only a branch inactive in a given build makes.
A use takes the types of every declaration that some build lets it see, so a
variable declared in a branch does not hide other declarations of it from uses
outside that branch. A type alias or Gazebo class defined differently in
alternative branches keeps one of its definitions.
"""

