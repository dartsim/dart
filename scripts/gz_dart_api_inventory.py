def strip_comments_and_strings(text):
    """Keep byte offsets and line numbers while hiding comments and literals."""
    return IGNORED.sub(lambda match: re.sub(r"[^\n]", " ", match.group()), text)


def preprocess(text):
    """Blank the branches that a literal `#if 0` or `#if 1` rules out.

    Other conditions are not evaluated, so all their branches stay. Returns the
    text and, for each line, the (conditional, branch) pairs that enclose it.
    """
    frames = []  # [conditional, branch, active, decided]
    lines, branches = [], []
    dead = continued = False
    for line in text.split("\n"):
        match = None if continued else CONDITIONAL.match(line)
        if match and (match[1].startswith("if") or frames):
            keyword, condition = match[1], match[2].strip()
            if keyword.startswith("if"):
                frames.append([len(branches), -1, True, False])
            frame = frames[-1]
            dead = not all(outer[2] for outer in frames[:-1])
            if keyword == "endif":
                frames.pop()
            else:
                literal = condition if keyword in {"if", "elif"} else None
                literal = "1" if keyword == "else" else literal
                frame[1] += 1
                frame[2] = not frame[3] and literal != "0"
                frame[3] = frame[3] or literal == "1"
        elif not continued:
            dead = not all(frame[2] for frame in frames)
        continued = line.rstrip().endswith("\\")
        lines.append(" " * len(line) if dead else line)
        branches.append(tuple((frame[0], frame[1]) for frame in frames))
    return "\n".join(lines), branches


def compatible(first, second):
    """Whether lines in these conditional branches can compile together."""
    branches = dict(first)
    return all(branches.get(key, branch) == branch for key, branch in second)


def strip_directives(text):
    result = []
    continuation = False
    for line in text.splitlines(keepends=True):
        directive = continuation or line.lstrip().startswith("#")
        continuation = directive and line.rstrip().endswith("\\")
        result.append(re.sub(r"[^\n]", " ", line) if directive else line)
    return "".join(result)


def header_macros(text):
    macros = {}
    text = text.replace("\\\n", " ")
    for match in re.finditer(
        r"^[ \t]*#[ \t]*define[ \t]+(_?DART_\w+)(\(([^)]*)\))?[ \t]*(.*)$",
        text,
        re.MULTILINE,
    ):
        parameters = (
            None if match[2] is None else [p.strip() for p in match[3].split(",")]
        )
        macros[match[1]] = (parameters, TOKEN.findall(match[4]))
    return macros


def expand_macros(values, macros, active=()):
    """Expand DART declaration macros, including token-pasted accessor names."""
    result = []
    i = 0
    while i < len(values):
        name = values[i]
        if name not in macros or name in active or len(active) >= 16:
            result.append(name)
            i += 1
            continue
        parameters, body = macros[name]
        end = i + 1
        arguments = []
        if parameters is not None:
            if end == len(values) or values[end] != "(":
                result.append(name)
                i += 1
                continue
            end += 1
            depth = 1
            argument = []
            while end < len(values) and depth:
                token = values[end]
                depth += (token == "(") - (token == ")")
                if depth == 0 or (token == "," and depth == 1):
                    arguments.append(argument)
                    argument = []
                else:
                    argument.append(token)
                end += 1
            if depth or len(arguments) != len(parameters):
                result.append(name)
                i += 1
                continue
        substitutions = dict(zip(parameters or [], arguments))
        replacement = []
        for token in body:
            replacement.extend(substitutions.get(token, [token]))
        pasted = []
        j = 0
        while j < len(replacement):
            if replacement[j] == "##" and pasted and j + 1 < len(replacement):
                pasted[-1] += replacement[j + 1]
                j += 2
            else:
                pasted.append(replacement[j])
                j += 1
        result.extend(expand_macros(pasted, macros, active + (name,)))
        i = end
    return result


def source_files(root):
    return sorted(
        path
        for path in root.rglob("*")
        if path.is_file()
        and ".git" not in path.parts
        and (path.suffix in CPP_SUFFIXES or path.name.endswith(".hpp.in"))
    )


@dataclass
class Tokens:
    text: str
    values: list = field(init=False)
    offsets: list = field(init=False)
    pairs: dict = field(init=False)
    enclosing: list = field(init=False)
    scopes: dict = field(default_factory=dict)
    bodies: dict = field(default_factory=dict)
    bindings: list = field(default_factory=list)
    branches: list = field(default_factory=list)
    aliases: dict = field(default_factory=dict)
    wrapped: set = field(default_factory=set)
    raw_pointers: set = field(default_factory=set)
    using: list = field(default_factory=list)
    template_headers: dict = field(default_factory=lambda: defaultdict(set))
    enum_headers: dict = field(default_factory=lambda: defaultdict(set))
    macros: set = field(default_factory=set)

    def __post_init__(self):
        matches = list(TOKEN.finditer(self.text))
        self.values = [match.group() for match in matches]
        self.offsets = [match.start() for match in matches]
        self.pairs = {}
        self.enclosing = []
        stack = []
        for i, value in enumerate(self.values):
            self.enclosing.append(stack[-1][1] if stack else None)
            if value in ("(", "{", "["):
                stack.append((value, i))
            elif value in (")", "}", "]") and stack:
                opening, index = stack[-1]
                if opening == {")": "(", "}": "{", "]": "["}[value]:
                    stack.pop()
                    self.pairs[index] = i
                    self.pairs[i] = index

    def line(self, index):
        return self.text.count("\n", 0, self.offsets[index]) + 1


def qualified(values):
    return "".join(values).lstrip(":")


def declaration(values, owner, macros=()):
    """Read a declaration prefix, before its semicolon or inline body."""
    square = brace = 0
    for opening, value in enumerate(values):
        square += (value == "[") - (value == "]")
        brace += (value == "{") - (value == "}")
        if square or brace or value != "(" or opening == 0:
            continue
        name_index = opening - 1
        name = values[name_index]
        for spelling in (
            ("operator", "->"),
            ("operator", "[", "]"),
            ("operator", "(", ")"),
        ):
            if tuple(values[max(0, opening - len(spelling)) : opening]) == spelling:
                name_index = opening - len(spelling)
                name = "".join(spelling)
                break
        if (
            not IDENTIFIER.match(name)
            and not name.startswith("operator")
            or name in {"operator", "decltype", "noexcept", "alignas"}
        ):
            continue
        if name in macros:
            continue
        depth = 1
        closing = opening + 1
        while closing < len(values) and depth:
            depth += (values[closing] == "(") - (values[closing] == ")")
            closing += 1
        if depth:
            continue
        prefix = values[:name_index]
        suffix = values[closing:]
        if ":" in suffix:  # a constructor's member initializers
            values = values[: closing + suffix.index(":")]
            suffix = values[closing:]
        angle = 0
        assignment = False
        for token in prefix:
            angle += (token == "<") - (token == ">")
            assignment |= token == "=" and angle == 0
        if assignment or "return" in prefix or "->" in prefix or "." in prefix:
            return None
        return {
            "class": owner,
            "name": name,
            "signature": " ".join(values),
            "const": "const" in suffix,
            "virtual": "virtual" in prefix or "override" in suffix,
            "override": "override" in suffix,
            "return_tokens": prefix,
            "name_index": name_index,
        }
    return None


def member_signature(item, resolve_type):
    """Parameter types and member cv/ref qualifiers, independent of specifiers."""
    if "static" in item["return_tokens"]:
        return None
    tokens = Tokens(item["signature"])
    values = tokens.values
    opening = len(item["return_tokens"]) + len(
        TOKEN.findall(item["name"].rsplit("::", 1)[-1])
    )
    closing = tokens.pairs.get(opening)
    if closing is None or values[opening] != "(":
        return None
    parameters, current, depth, default = [], [], 0, False
    for value in values[opening + 1 : closing] + [","]:
        if value == "," and depth == 0:
            parameters.append(current)
            current, default = [], False
            continue
        if value == "=" and depth == 0:
            default = True
        depth += (value in {"<", "(", "["}) - (value in {">", ")", "]"})
        if not default:
            current.append(value)
    normalized = []
    keywords = {
        "const",
        "volatile",
        "void",
        "bool",
        "char",
        "signed",
        "unsigned",
        "short",
        "int",
        "long",
        "float",
        "double",
        "wchar_t",
        "char16_t",
        "char32_t",
    }
    for parameter in parameters:
        if (
            len(parameter) > 1
            and IDENTIFIER.match(parameter[-1])
            and parameter[-1] not in keywords
            and parameter[-2] != "::"
            and any(value not in {"const", "volatile"} for value in parameter[:-1])
        ):
            parameter = parameter[:-1]
        top, angle = [], 0
        for index, value in enumerate(parameter):
            if angle == 0:
                top.append(index)
            angle += (value == "<") - (value == ">")
        # By-value parameters discard top-level cv qualifiers in C++ signatures.
        if not any(parameter[index] in {"&", "&&"} for index in top):
            pointer = max((i for i in top if parameter[i] == "*"), default=-1)
            parameter = [
                value
                for i, value in enumerate(parameter)
                if not (i in top and i > pointer and value in {"const", "volatile"})
            ]
        result, end = [], 0
        for start, stop, name in names_in(parameter):
            result.extend(parameter[end:start])
            resolved = resolve_type(name)
            result.extend([resolved] if resolved else parameter[start:stop])
            end = stop
        result.extend(parameter[end:])
        if result and result != ["void"]:
            normalized.append(tuple(result))
    suffix = []
    for value in values[closing + 1 :]:
        if value not in {"const", "volatile", "&", "&&"}:
            break
        suffix.append(value)
    return (
        tuple(normalized),
        "const" in suffix,
        "volatile" in suffix,
        tuple(value for value in suffix if value in {"&", "&&"}),
    )


def data_member(values, owner):
    """Read one data declarator, including its array dimensions."""
    declarator = values
    angle = 0
    for end, token in enumerate(values):
        angle += (token == "<") - (token == ">")
        if token in {"=", "{"} and angle == 0:
            declarator = values[:end]
            break
    tokens = Tokens(" ".join(declarator))
    end = len(declarator)
    while end and declarator[end - 1] == "]" and end - 1 in tokens.pairs:
        end = tokens.pairs[end - 1]
    if (
        len(declarator[:end]) < 2
        or not IDENTIFIER.match(declarator[end - 1])
        or not NOT_DATA.isdisjoint(declarator[:end])
    ):
        return None
    top, angle = [], 0  # the type's tokens outside template arguments
    for token in declarator[: end - 1]:
        if angle == 0:
            top.append(token)
        angle += (token == "<") - (token == ">")
    pointer = max((k for k, t in enumerate(top) if t in {"*", "&", "&&"}), default=-1)
    return {
        "class": owner,
        "name": declarator[end - 1],
        "name_index": end - 1,
        "static": "static" in top,
        "return_tokens": declarator[: end - 1],
        "signature": " ".join(values),
        "const": "constexpr" in top or "const" in top[pointer + 1 :],
        "virtual": False,
    }


def data_declarations(values, owner):
    """Split grouped declarators while retaining their shared type."""
    tokens = Tokens(" ".join(values))
    parts, start, i, angle = [], 0, 0, 0
    while i <= len(values):
        if i == len(values) or values[i] == "," and angle == 0:
            parts.append(values[start:i])
            start = i + 1
        elif values[i] in {"(", "[", "{"} and i in tokens.pairs:
            i = tokens.pairs[i]
        else:
            angle += (values[i] == "<") - (values[i] == ">")
        i += 1
    first = data_member(parts[0], owner)
    if not first:
        return []
    end = first["name_index"]
    shared = parts[0][:end]
    angle = 0
    for i, token in enumerate(shared):
        if angle == 0 and token in {"*", "&", "&&"}:
            shared = shared[:i]
            break
        angle += (token == "<") - (token == ">")
    return [first] + [
        member for part in parts[1:] if (member := data_member(shared + part, owner))
    ]


def qualifier_path(values, end=None):
    """The `A::B::` qualifier that ends a declaration prefix, as ("A", "B")."""
    path = []
    end = len(values) if end is None else end
    end -= values[end - 1 : end] == ["~"]
    while end > 1 and values[end - 1] == "::":
        k = end - 2
        if values[k] == ">":  # the template arguments of `A<T>::`
            depth = 1
            while k > 0 and depth:
                k -= 1
                depth += (values[k] == ">") - (values[k] == "<")
            k -= 1
        if k < 0 or not IDENTIFIER.match(values[k]):
            break
        path.insert(0, values[k])
        end = k
    return tuple(path)


def member_initializer(tokens, segment, index):
    """Whether the `{` at `index` braces `m{...}` after a constructor's `(...) :`."""
    values = tokens.values
    if not (IDENTIFIER.match(values[index - 1]) or values[index - 1] == ">"):
        return False
    i, parameters = segment, False
    while i < index:  # a top-level colon after the parameter list
        if values[i] == "(" and i in tokens.pairs:
            i, parameters = tokens.pairs[i] + 1, True
            continue
        if values[i] == ":" and parameters:
            return True
        i += 1
    return False


def scopes(tokens):
    """Collect namespace/class spans and direct member declaration prefixes.

    Members of every access are returned with their `access`; out-of-line member
    definitions get their class's scope for their parameters and bodies.
    """
    values = tokens.values
    classes = []
    functions = []
    aliases = []
    fields = []

    def walk(start, end, namespace=(), owner=None, access="public"):
        here = tuple(owner.split("::")) if owner else namespace
        i = start
        segment = start
        while i < end:
            tokens.scopes[i] = here
            value = values[i]
            if (
                value in {"public", "protected", "private"}
                and i + 1 < end
                and values[i + 1] == ":"
            ):
                access = value
                i += 2
                segment = i
                continue
            if value == "namespace":
                j = i + 1
                while j < end and (IDENTIFIER.match(values[j]) or values[j] == "::"):
                    j += 1
                if j < end and values[j] == "{" and j in tokens.pairs:
                    names = tuple(v for v in values[i + 1 : j] if v != "::")
                    tokens.bodies[j] = namespace + names
                    walk(j + 1, tokens.pairs[j], namespace + names)
                    i = tokens.pairs[j] + 1
                    segment = i
                    continue
            if value in {"class", "struct", "enum"} and i + 1 < end:
                j = i + 1
                scoped_enum = value == "enum" and values[j] in {"class", "struct"}
                if scoped_enum:
                    j += 1
                while j < end:
                    if values[j] in {"[", "("} and j in tokens.pairs:
                        j = tokens.pairs[j] + 1
                    elif j + 1 < end and (
                        values[j] in {"alignas", "__attribute__", "__declspec"}
                        or (values[j].startswith("DART_") or values[j].isupper())
                        and (
                            values[j + 1] == "("
                            or IDENTIFIER.match(values[j + 1])
                            and values[j + 1] != "final"
                        )
                    ):
                        j += 1
                    else:
                        break
                if j < end and IDENTIFIER.match(values[j]):
                    name = values[j]
                    k = template_end(values, j + 1)  # a specialization's arguments
                    final = k < end and values[k] == "final"
                    if final:
                        k += 1
                    if k < end and values[k] in {"{", ":", ";"}:
                        parent_start = k + 1
                        while k < end and values[k] not in {"{", ";"}:
                            k += 1
                        full_name = "::".join(
                            (owner or "::".join(namespace), name)
                        ).strip(":")
                        if value == "enum":
                            tokens.enum_headers[full_name].add(" ".join(values[i:k]))
                        if values[segment : segment + 2] == ["template", "<"]:
                            stop, angle = segment + 1, 0
                            while stop < i:
                                if (
                                    values[stop] in {"(", "[", "{"}
                                    and stop in tokens.pairs
                                ):
                                    stop = tokens.pairs[stop] + 1
                                    continue
                                angle += (values[stop] == "<") - (values[stop] == ">")
                                stop += 1
                                if angle == 0:
                                    break
                            if angle == 0:
                                tokens.template_headers[full_name].add(
                                    " ".join(
                                        values[segment:stop]
                                        + values[i : template_end(values, j + 1)]
                                    )
                                )
                        if k < end and values[k] == "{" and k in tokens.pairs:
                            tokens.bodies[k] = tuple(full_name.split("::"))
                            parents = []
                            angle = 0
                            for p in range(parent_start, k + 1):
                                current = values[p] if p < k else ","
                                angle += (current == "<") - (current == ">")
                                if current == "," and angle == 0:
                                    parents.append(" ".join(values[parent_start:p]))
                                    parent_start = p + 1
                            entry = {
                                "name": full_name,
                                "kind": value,
                                "final": final,
                                "bases": parents,
                                "members": [],
                                "index": i,
                                "body": k,
                                "end": tokens.pairs[k],
                            }
                            classes.append(entry)
                            if value == "enum":
                                begin = p = k + 1
                                stop = tokens.pairs[k]
                                while p <= stop:
                                    if p < stop and values[p] in {"(", "[", "{"}:
                                        p = tokens.pairs.get(p, p) + 1
                                        continue
                                    if p == stop or values[p] == ",":
                                        if begin < p and IDENTIFIER.match(
                                            values[begin]
                                        ):
                                            member = {
                                                "class": full_name,
                                                "name": values[begin],
                                                "signature": " ".join(values[begin:p]),
                                                "const": True,
                                                "virtual": False,
                                                "enum_type": full_name,
                                                "enum_declaration": " ".join(
                                                    values[i:k]
                                                ),
                                            }
                                            fields.append(member)
                                            if not scoped_enum:
                                                fields.append(
                                                    {
                                                        **member,
                                                        "class": owner
                                                        or "::".join(namespace),
                                                    }
                                                )
                                        begin = p + 1
                                    p += 1
                            else:
                                before = len(functions)
                                walk(
                                    k + 1,
                                    tokens.pairs[k],
                                    namespace,
                                    full_name,
                                    "public" if value == "struct" else "private",
                                )
                                entry["members"] = [
                                    m
                                    for m in functions[before:]
                                    if m["class"] == full_name
                                ]
                            i = tokens.pairs[k] + 1
                            segment = i
                            continue
                        if k < end and values[k] == ";":
                            aliases.append((full_name, [full_name], i))
            initializer = value == "{" and (
                member_initializer(tokens, segment, i)
                or bool(
                    data_declarations(values[segment:i], owner or "::".join(namespace))
                )
            )
            if (value == "(" or initializer) and i in tokens.pairs:
                for p in range(i, tokens.pairs[i] + 1):
                    tokens.scopes[p] = here
                i = tokens.pairs[i] + 1
                continue
            if value in {";", "{"}:
                prefix = values[segment:i]
                method = declaration(prefix, owner, tokens.macros)
                inside, scope = i, here
                if method:
                    method["index"] = segment
                    method["name_index"] += segment
                    method["access"] = access
                    path = qualifier_path(method["return_tokens"])
                    if owner is None:
                        method["name"] = "::".join(namespace + path + (method["name"],))
                        if path and value == "{" and i in tokens.pairs:
                            # An out-of-line definition looks names up in A::B,
                            # which scan_sources resolves to the declared class.
                            inside, scope = method["name_index"] + 1, namespace + path
                            method["definition"] = (
                                namespace,
                                path,
                                inside,
                                tokens.pairs[i],
                            )
                    functions.append(method)
                elif owner is None or access != "private":
                    fields.extend(
                        {**member, "access": access}
                        for member in data_declarations(
                            prefix, owner or "::".join(namespace)
                        )
                    )
                if prefix and "using" in prefix and "=" in prefix:
                    equals = prefix.index("=")
                    using = prefix.index("using")
                    aliases.append(
                        (
                            "::".join(
                                (owner or "::".join(namespace), prefix[using + 1])
                            ).strip(":"),
                            prefix[equals + 1 :],
                            segment,
                        )
                    )
                elif prefix and prefix[0] == "typedef" and len(prefix) > 2:
                    aliases.append(
                        (
                            "::".join(
                                (owner or "::".join(namespace), prefix[-1])
                            ).strip(":"),
                            prefix[1:-1],
                            segment,
                        )
                    )
                if value == "{" and i in tokens.pairs:
                    # shortcut: local classes are omitted; add lexical identities when local adapters need inventory coverage.
                    for p in range(inside, tokens.pairs[i] + 1):
                        tokens.scopes[p] = scope
                    i = tokens.pairs[i] + 1
                else:
                    i += 1
                segment = i
                continue
            i += 1

    walk(0, len(values))
    return classes, functions, aliases, fields


@dataclass
class ApiIndex:
    types: set = field(default_factory=set)
    type_templates: dict = field(default_factory=lambda: defaultdict(set))
    type_enums: dict = field(default_factory=lambda: defaultdict(set))
    classes: dict = field(default_factory=dict)
    members: dict = field(default_factory=lambda: defaultdict(list))
    constructors: dict = field(default_factory=dict)
    declares_constructor: set = field(default_factory=set)
    data_members: dict = field(default_factory=lambda: defaultdict(list))
    brace_fields: dict = field(default_factory=lambda: defaultdict(list))
    variables: dict = field(default_factory=lambda: defaultdict(list))
    free_functions: dict = field(default_factory=lambda: defaultdict(list))
    aliases: dict = field(default_factory=dict)
    macros: set = field(default_factory=set)
    headers: set = field(default_factory=set)
    dependencies: dict = field(default_factory=dict)
    standard_pointers: set = field(default_factory=set)
    wrappers: set = field(default_factory=set)
    raw_pointers: set = field(default_factory=set)

    def spellings(self, name, scope=(), imports=()):
        """Qualified spellings of `name`, from the innermost scope outward."""
        name = re.sub(r"\s+", "", name).lstrip(":")
        return [
            *("::".join(scope[:size] + (name,)) for size in range(len(scope), -1, -1)),
            *(namespace + "::" + name for namespace in imports),
        ]

    def find(self, name, scope=(), imports=(), aliases=None):
        """The type that `name` names in `scope`, and the alias it names."""
        for candidate in self.spellings(name, scope, imports):
            if aliases and candidate in aliases:
                return aliases[candidate], candidate
            if candidate in self.types:
                return candidate, None
        return None, None

    def resolve(self, name, scope=(), imports=(), aliases=None):
        return self.find(name, scope, imports, aliases)[0]

    def owner(self, name):
        seen = set()
        while name in self.aliases and name not in seen:
            seen.add(name)
            name = self.aliases[name]
        if name in self.classes:
            return name
        return None

    def constructible(self, name):
        """The class that `name` constructs, unless an alias only wraps it."""
        seen = set()
        while name in self.aliases and name not in seen:
            if name in self.wrappers:
                return None
            seen.add(name)
            name = self.aliases[name]
        return name if name in self.constructors else None

    def constructor_declarations(self, name):
        """The constructors a construction of class `name` can call.

        A class that declares no constructor has an implicit one, which calls
        the constructors of its bases.
        """
        result, pending, seen = [], [name], set()
        while pending:
            current = pending.pop(0)
            if current in seen:
                continue
            seen.add(current)
            result += self.constructors.get(current, [])
            if current not in self.declares_constructor:
                bases = self.classes.get(current, {}).get("bases", ())
                pending += [base for base in map(self.owner, bases) if base]
        return result

    def ancestors(self, name):
        result = set()
        seen = set()
        pending = [name]
        while pending:
            current = pending.pop()
            if not current or current in seen:
                continue
            seen.add(current)
            pending.extend(self.dependencies.get(current, ()))
            if current in self.aliases:
                pending.append(self.aliases[current])
            if current in self.classes:
                result.add(current)
                pending.extend(self.classes[current]["bases"])
        return result


def names_in(values):
    i = 0
    while i < len(values):
        if IDENTIFIER.match(values[i]):
            end = i + 1
            while (
                end + 1 < len(values)
                and values[end] == "::"
                and IDENTIFIER.match(values[end + 1])
                and values[i]
                not in {
                    "const",
                    "volatile",
                    "typename",
                    "return",
                    "class",
                    "struct",
                    "static",
                    "virtual",
                    "public",
                    "protected",
                    "private",
                    "using",
                    "namespace",
                    "typedef",
                    "new",
                    "delete",
                }
            ):
                end += 2
            yield i, end, qualified(values[i:end])
            i = end
        else:
            i += 1


def wraps(values, direct):
    """Whether an alias definition is a pointer, reference or non-DART template."""
    named = [v for _, _, v in names_in(values) if v not in {"const", "typename"}]
    return not named or not direct(named[0]) or not {"*", "&", "&&"}.isdisjoint(values)


def raw_pointer(values):
    """Whether the declarator is a pointer, excluding template arguments."""
    depth = 0
    for value in values:
        if value == "*" and depth == 0:
            return True
        depth += (value in {"<", "(", "["}) - (value in {">", ")", "]"})
    return False


def base_name(raw):
    """The class named in a base clause entry such as `public virtual A<B>`."""
    raw = re.sub(r"\b(public|protected|private|virtual)\b", "", raw)
    return re.sub(r"\s+", "", raw).split("<")[0]


def expand(name, namespace_aliases):
    """Replace a namespace alias at the head of a qualified name."""
    head, _, tail = name.partition("::")
    if head not in namespace_aliases:
        return name
    return namespace_aliases[head] + ("::" + tail if tail else "")


def template_end(values, index):
    """Skip the template argument list, if any, that starts at `index`."""
    if index < len(values) and values[index] == "<":
        depth = 1
        index += 1
        while index < len(values) and depth:
            depth += (values[index] == "<") - (values[index] == ">")
            index += 1
    return index


def variable_after_type(values, end):
    j = template_end(values, end)
    while j < len(values) and values[j] in {"const", "*", "&", "&&", ">"}:
        j += 1
    while j + 2 < len(values) and IDENTIFIER.match(values[j]) and values[j + 1] == "::":
        j += 2  # the `Class::` of an out-of-line static member definition
    if (
        j + 1 < len(values)
        and IDENTIFIER.match(values[j])
        and values[j + 1] in {";", "=", ",", ")", "(", "{", "["}
    ):
        return j
    return None


def array_end(tokens, index):
    """Skip balanced array declarator dimensions starting at `index`."""
    while tokens.values[index : index + 1] == ["["] and index in tokens.pairs:
        index = tokens.pairs[index] + 1
    return index


def in_template_argument(values, start):
    angle = 0
    for index in range(start - 1, -1, -1):
        if values[index] in {";", "{", "}"}:
            break
        angle += (values[index] == "<") - (values[index] == ">")
    return angle > 0


def constructs(tokens, start, end, declarations, heads):
    """Whether the type named by values[start:end] is constructed there."""
    values = tokens.values
    lead = start - (start > 0 and values[start - 1] == "::")  # `::dart::...`
    before = values[lead - 1] if lead else None
    after = template_end(values, end)
    for head, body in heads:
        if head < start < body:  # a base's constructors run for the class's
            nesting = sum((v == "<") - (v == ">") for v in values[head:start])
            return (
                before in {":", ",", "public", "protected", "private", "virtual"}
                and values[after : after + 1] in (["{"], [","])
                and nesting == 0  # not a template argument
            )
    if before in {".", "->", "~", "operator"}:
        return False
    if (
        before == "<"
        and lead > 1
        and values[lead - 2] in {"make_shared", "make_unique"}
    ):
        return values[after : after + 2] == [">", "("]
    if before == "using":  # inherited constructors
        return values[end : end + 2] == ["::", values[end - 1]]
    if in_template_argument(values, start):
        return False
    variable = variable_after_type(values, end)
    statement = lead  # the specifiers of the declaration that the type starts
    while statement and values[statement - 1] not in {
        ";",
        "{",
        "}",
        ":",
        "(",
        ",",
        "=",
    }:
        statement -= 1
    specifiers = set(values[statement:lead])
    initialized = array_end(tokens, variable + 1) if variable is not None else 0
    defined = variable is not None and values[initialized : initialized + 1] in (
        ["="],
        ["{"],
        ["("],
    )
    if (
        specifiers & {"typedef", "friend"}
        or ("extern" in specifiers and not defined)
        or (  # an in-class declaration, defined out of line
            "static" in specifiers
            and not specifiers & {"inline", "constexpr"}
            and any(tokens.enclosing[start] == body for _, body in heads)
        )
    ):
        return False
    if before == "new" or values[after : after + 1] in (["("], ["{"]):
        return True
    opening = tokens.enclosing[start]  # parameters are not constructions
    return (
        variable is not None
        and variable not in declarations
        and (
            opening is None
            or values[opening] != "("
            or values[opening - 1] in {"if", "for", "while", "switch", "constexpr"}
        )
        and {"*", "&", "&&"}.isdisjoint(values[after:variable])
    )


def using_declarations(tokens):
    """(name, target, scope, start, stop, depth) for each using import.

    A declaration is visible at tokens start..stop within `scope` and declares
    the name at `depth`, the length of its namespace or class scope, or past
    `BLOCK` in a block. A namespace directive has no single imported name.
    """
    values = tokens.values
    result = []
    for i in range(len(values) - 1):
        if values[i] != "using" or values[i + 1] == "typename":
            continue
        directive = values[i + 1] == "namespace"
        start = i + 1 + directive
        j = start
        while j < len(values) and (IDENTIFIER.match(values[j]) or values[j] == "::"):
            j += 1
        if values[j : j + 1] != [";"] or (not directive and "::" not in values[i:j]):
            continue
        name = None if directive else values[j - 1]
        target = qualified(values[start:j])
        scope = tokens.scopes.get(i, ())
        opening = tokens.enclosing[i]
        if opening is None or opening in tokens.bodies:
            result.append((name, target, scope, i, len(values), len(scope)))
        elif values[opening] == "{":  # an inner block lies deeper than outer ones
            stop = tokens.pairs.get(opening, len(values))
            result.append((name, target, scope, i, stop, BLOCK + opening))
    return result


def elements(types):
    """Element types of the DART containers among `types`."""
    return {
        t.removeprefix("__element__:") for t in types if t.startswith("__element__:")
    }


def first_template_argument(values, start):
    if start >= len(values) or values[start] != "<":
        return []
    depth = 1
    end = start + 1
    while end < len(values):
        token = values[end]
        if depth == 1 and token in {",", ">"}:
            break
        depth += (token == "<") - (token == ">")
        end += 1
    return values[start + 1 : end]


def container_elements(argument, api, resolve_type, pointer_type=None):
    """DART element markers, including the element's raw-pointer identity."""
    result = set()
    pointer = raw_pointer(argument)
    for _, _, value in names_in(argument):
        resolved = resolve_type(value)
        if api.owner(resolved):
            result.add("__element__:" + resolved)
            pointer |= resolved in api.raw_pointers or bool(
                pointer_type and pointer_type(value)
            )
    if result and pointer:
        result.add("__element__:" + RAW_POINTER)
    return result


def bind_variable(tokens, index, types):
    """Explicit declarations shadow same-named fields and other functions."""
    values = tokens.values
    start, end = 0, len(values)
    for opening, closing in tokens.pairs.items():
        if opening >= closing or not opening < index < closing:
            continue
        if values[opening] == "{" and closing - opening < end - start:
            start, end = opening, closing
        elif (
            values[opening] == "("
            and opening
            and (
                IDENTIFIER.match(values[opening - 1])
                or values[opening - 1] == "]"
                and opening - 1 in tokens.pairs
            )
        ):
            body = closing + 1
            while body < len(values) and values[body] in {
                "const",
                "override",
                "final",
                "noexcept",
                "mutable",
            }:
                body += 1
                if body < len(values) and values[body] == "(" and body in tokens.pairs:
                    body = tokens.pairs[body] + 1
            if body < len(values) and values[body] == "->":
                body += 1
                while body < len(values) and values[body] not in {"{", ";", "="}:
                    if values[body] in {"(", "["} and body in tokens.pairs:
                        body = tokens.pairs[body] + 1
                    else:
                        body += 1
            if body < len(values) and values[body] == "{" and body in tokens.pairs:
                if tokens.pairs[body] - opening < end - start:
                    start, end = opening, tokens.pairs[body]
    tokens.bindings.append((start, end, index, values[index], types))


def variable_types(tokens, index, fields):
    if index and tokens.values[index - 1] in {"->", "."}:
        return set(fields.get(tokens.values[index], ()))
    branches = tokens.branches
    bindings = sorted(
        (
            b
            for b in tokens.bindings
            if b[0] <= index <= b[1]
            and b[2] <= index
            and b[3] == tokens.values[index]
            and compatible(branches[b[2]], branches[index])
        ),
        key=lambda b: (b[1] - b[0], -b[2]),
    )
    types = set()
    for b in bindings:  # innermost first
        types |= b[4]
        # A declaration that only some builds compile hides the others in those
        # builds alone: alternatives and outer declarations stay visible.
        if set(branches[b[2]]) <= set(branches[index]):
            return types
    return types | set(fields.get(tokens.values[index], ()))


def is_field(tokens, index, classes):
    start = tokens.bindings[-1][0]
    return any(start == cls["body"] for cls in classes) and not any(
        opening < index < closing and tokens.values[opening] == "("
        for opening, closing in tokens.pairs.items()
        if opening < closing
    )


def index_api(header_root):
    api = ApiIndex()
    pending_aliases = []
    macros = {}
    headers = []
    declaration_macros = set()
    for path in source_files(Path(header_root)):
        if path.suffix not in {
            ".h",
            ".hh",
            ".hpp",
            ".hxx",
            ".ipp",
            ".tpp",
        } and not path.name.endswith(".hpp.in"):
            continue
        text = path.read_text(encoding="utf-8")
        api.headers.add(
            "dart/" + path.relative_to(header_root).as_posix().removesuffix(".in")
        )
        clean = preprocess(strip_comments_and_strings(text))[0]
        declaration_macros.update(
            re.findall(r"^\s*#\s*define\s+(\w+)", clean, re.MULTILINE)
        )
        api.macros.update(
            re.findall(r"^\s*#\s*define\s+(DART_\w+)", clean, re.MULTILINE)
        )
        macros.update(header_macros(clean))
        headers.append(strip_directives(clean))
    for clean in headers:
        tokens = Tokens(" ".join(expand_macros(TOKEN.findall(clean), macros)))
        tokens.macros = declaration_macros
        classes, functions, aliases, fields = scopes(tokens)
        for name, declarations in tokens.template_headers.items():
            if name.startswith("dart::"):
                api.type_templates[name].update(declarations)
        for name, declarations in tokens.enum_headers.items():
            if name.startswith("dart::"):
                api.type_enums[name].update(declarations)
        for cls in classes:
            if cls["name"].startswith("dart::"):
                api.types.add(cls["name"])
                # Specializations and alternative definitions share one entry.
                entry = api.classes.setdefault(
                    cls["name"], {"bases_raw": [], "bases": [], "final": False}
                )
                entry["bases_raw"] += cls["bases"]
                entry["final"] |= cls["final"]
                if cls["kind"] != "enum":
                    api.constructors.setdefault(cls["name"], [])
        for name, values, _ in aliases:
            if name.startswith("dart::"):
                api.types.add(name)
                pending_aliases.append((name, values))
                if any(
                    value in {"std::shared_ptr", "std::unique_ptr", "std::weak_ptr"}
                    for _, _, value in names_in(values)
                ):
                    api.standard_pointers.add(name)
        for function in functions:
            owner = function["class"]
            public = function["access"] != "private"
            if owner and owner.startswith("dart::"):
                if function["name"] != owner.split("::")[-1]:
                    if public or function["virtual"]:
                        api.members[function["name"]].append(function)
                elif "~" not in function["return_tokens"]:
                    api.declares_constructor.add(owner)
                    if public:
                        api.constructors.setdefault(owner, []).append(function)
            elif (
                owner is None
                and function["name"].startswith("dart::")
                and function["return_tokens"][-1:] != ["::"]  # not Class::member
            ):
                api.free_functions[function["name"]].append(function)
        for member in fields:
            if member["class"] == "dart" or member["class"].startswith("dart::"):
                if member["class"] in api.classes:
                    api.data_members[member["name"]].append(member)
                    if member.get("access") == "public" and not member.get("static"):
                        api.brace_fields[member["class"]].append(member)
                else:
                    api.variables[member["class"] + "::" + member["name"]].append(
                        member
                    )
    for name, values in pending_aliases:
        scope = tuple(name.split("::")[:-1])
        for _, _, value in names_in(values):
            resolved = api.resolve(value, scope)
            if resolved and resolved != name:
                api.aliases.setdefault(name, resolved)
                api.dependencies.setdefault(name, set()).add(resolved)
        if wraps(values, lambda value: api.resolve(value, scope)):
            api.wrappers.add(name)
        if raw_pointer(values):
            api.raw_pointers.add(name)
    pending = set(api.aliases)
    while pending:
        raw = {name for name in pending if api.aliases[name] in api.raw_pointers}
        standard = {
            name for name in pending if api.aliases[name] in api.standard_pointers
        }
        found = raw | standard
        api.raw_pointers.update(raw)
        api.standard_pointers.update(standard)
        pending -= found
        if not found:
            break
    for name, cls in api.classes.items():
        scope = tuple(name.split("::")[:-1])
        for raw in cls.pop("bases_raw"):
            for _, _, value in names_in(TOKEN.findall(raw)):
                resolved = api.resolve(value, scope)
                if resolved and resolved != name:
                    cls["bases"].append(resolved)
    api.free_functions = {
        name: declarations
        for name, declarations in api.free_functions.items()
        if name not in api.types
    }
    return api


def classify_member(name, declarations):
    if declarations and all(item["const"] for item in declarations):
        return "accessor"
    getter = re.match(r"^(get|is|has|num)(?:[A-Z_]|$)", name)
    effect = re.search(
        r"(?:Create|Reset|Clear|Remove|Add|Update|Set|Release|Claim|Erase)", name
    )
    return "accessor" if getter and not effect else "mutation"


def public_declaration(declaration):
    return {
        key: declaration[key]
        for key in (
            "class",
            "signature",
            "const",
            "virtual",
            "enum_type",
            "enum_declaration",
        )
        if key in declaration
    }


def scan_sources(api, source_root):
    source_root = Path(source_root)
    files = []
    includes = {}
    targets = defaultdict(dict)
    fields = defaultdict(set)
    local_bases = {}
    source_returns = defaultdict(list)
    source_macros = set()
    referenced = set()
    tables = {
        section: {}
        for section in (
            "types",
            "headers",
            "members",
            "constructors",
            "data_members",
            "variables",
            "free_functions",
            "macros",
            "overrides",
        )
    }

    def add(section, name, path, line, **metadata):
        row = tables[section].setdefault(
            name, {"name": name, "count": 0, "examples": set(), **metadata}
        )
        row["count"] += 1
        row["examples"].add(f"{path}:{line}")
        return row

    for path in source_files(source_root):
        relative = path.relative_to(source_root).as_posix()
        text = path.read_text(encoding="utf-8")
        clean, branches = preprocess(strip_comments_and_strings(text))
        includes[relative] = [
            match[1]
            for match in INCLUDE.finditer(text)
            if "include" in clean[match.start() : match.start(1)]
        ]
        for match in INCLUDE.finditer(text):
            if (
                match[1].startswith("dart/")
                and "include" in clean[match.start() : match.start(1)]
            ):
                add(
                    "headers",
                    match[1],
                    relative,
                    text.count("\n", 0, match.start()) + 1,
                    source_present=match[1] in api.headers,
                )
        source_macros.update(
            re.findall(r"^\s*#\s*define\s+(DART_\w+)", clean, re.MULTILINE)
        )
        tokens = Tokens(clean)
        tokens.macros = api.macros | set(
            re.findall(r"^\s*#\s*define\s+(\w+)", clean, re.MULTILINE)
        )
        line = 0
        newlines = [match.start() for match in re.finditer("\n", clean)]
        for offset in tokens.offsets:
            while line < len(newlines) and newlines[line] < offset:
                line += 1
            tokens.branches.append(branches[line])
        classes, functions, source_aliases, _ = scopes(tokens)
        imports = re.findall(r"\busing\s+namespace\s+([\w:]+)\s*;", clean)
        namespace_aliases = dict(
            re.findall(r"\bnamespace\s+(\w+)\s*=\s*([\w:]+)\s*;", clean)
        )
        files.append(
            (
                relative,
                tokens,
                classes,
                functions,
                source_aliases,
                imports,
                namespace_aliases,
            )
        )
    for path in sorted(source_root.rglob("CMakeLists.txt")):
        for definitions in re.findall(
            r"\btarget_compile_definitions\s*\(([^)]*)\)",
            path.read_text(encoding="utf-8"),
            re.DOTALL,
        ):
            source_macros.update(re.findall(r"\bDART_\w+", definitions))

    # A file sees the declarations of the scanned headers it includes, transitively.
    suffixes = defaultdict(list)
    for relative in includes:
        parts = relative.split("/")
        for start in range(len(parts)):
            suffixes["/".join(parts[start:])].append(relative)
    closure = {}
    for relative in includes:
        seen, pending = set(), [relative]
        while pending:
            current = pending.pop()
            for name in includes[current]:
                local = posixpath.normpath(
                    posixpath.join(posixpath.dirname(current), name)
                )
                for header in [local] if local in includes else suffixes[name]:
                    if header not in seen:
                        seen.add(header)
                        pending.append(header)
        closure[relative] = sorted(seen - {relative}) + [relative]
    own = {
        path: (list(imports), dict(namespace_aliases))
        for path, tokens, _, _, _, imports, namespace_aliases in files
    }
    for path, tokens, _, _, _, imports, namespace_aliases in files:
        imports.clear()
        for header in reversed(closure[path]):  # the file's own first
            spaces, renamed = own[header]
            imports += [space for space in spaces if space not in imports]
            for key, value in renamed.items():
                namespace_aliases.setdefault(key, value)
        imports[:] = [expand(space.lstrip(":"), namespace_aliases) for space in imports]
        if "dart" in imports:
            imports += ["dart::" + space for space in imports if space != "dart"]
    # An out-of-line definition `A::B::f` looks names up in the class A::B.
    known = {"::".join(s) for _, tokens, *_ in files for s in tokens.bodies.values()}
    for _, tokens, _, functions, _, imports, namespace_aliases in files:
        for function in functions:
            if "definition" in function:
                outer, qualifier, first, last = function["definition"]
                spelled = expand("::".join(qualifier), namespace_aliases)
                owner = next(
                    (c for c in api.spellings(spelled, outer, imports) if c in known),
                    "::".join(outer + qualifier),
                )
                for index in range(first, last + 1):
                    tokens.scopes[index] = tuple(owner.split("::"))
                function["name"] = owner + "::" + function["name"].rpartition("::")[2]
        tokens.using = using_declarations(tokens)
    declared_using = {path: list(tokens.using) for path, tokens, *_ in files}
    for path, tokens, *_ in files:  # and an included header's namespace-scope ones
        tokens.using += [
            (*entry[:3], -1, len(tokens.values), entry[5])
            for header in closure[path]
            if header != path
            for entry in declared_using[header]
            if entry[5] < BLOCK
        ]
    declared = defaultdict(lambda: defaultdict(set))
    for path, _, _, functions, *_ in files:
        for function in functions:
            scope = function["class"] or function["name"].rpartition("::")[0]
            source_returns[(scope, function["name"].split("::")[-1])].append(function)
            declared[path][function["name"].split("::")[-1]].add(
                tuple(scope.split("::")) if scope else ()
            )

    # Base classes declared in the scanned sources, for inherited names.
    source_classes = {cls["name"] for _, _, classes, *_ in files for cls in classes}
    renamed_classes = {}  # source aliases, which may name source classes
    for _, tokens, _, _, source_aliases, imports, namespace_aliases in files:
        for name, values, index in source_aliases:
            for _, _, value in names_in(values):
                where = tokens.scopes.get(index, ())
                renamed_classes.setdefault(
                    name, (value, where, imports, namespace_aliases)
                )
                break

    def source_class(name, scope, imports, namespace_aliases, depth=0):
        """The scanned class that `name` names in `scope`, through aliases."""
        for candidate in api.spellings(expand(name, namespace_aliases), scope, imports):
            if candidate in source_classes:
                return candidate
            if candidate in renamed_classes and depth < 8:
                return source_class(*renamed_classes[candidate], depth + 1)
        return None

    parents = defaultdict(list)
    for _, tokens, classes, _, _, imports, namespace_aliases in files:
        for cls in classes:
            for raw in cls["bases"]:
                scope = tokens.scopes.get(cls["index"], ())
                parent = source_class(base_name(raw), scope, imports, namespace_aliases)
                if parent and parent != cls["name"]:
                    parents[cls["name"]].append(parent)
    ancestry = {}
    for name in parents:
        ancestry[name], pending = [], list(parents[name])
        while pending:
            parent = pending.pop(0)
            if parent not in ancestry[name] and parent != name:
                ancestry[name].append(parent)
                pending += parents.get(parent, ())

    def publish(tokens, name, target, wrapper, pointer):
        tokens.aliases[name] = target
        (tokens.wrapped.add if wrapper else tokens.wrapped.discard)(name)
        (tokens.raw_pointers.add if pointer else tokens.raw_pointers.discard)(name)

    def visible(relative, tokens):
        tokens.aliases, tokens.wrapped = {}, set()
        tokens.raw_pointers = set()
        for owner in closure[relative]:
            for name, (target, wrapper, pointer) in targets[owner].items():
                publish(tokens, name, target, wrapper, pointer)

    def lookup(name, tokens, index, imports, namespace_aliases):
        """The DART type that `name` names there, and the source alias it uses.

        Lookup follows C++ name lookup lexically: enclosing scopes from the
        innermost, the bases of enclosing classes, then `Outer::Nested` names
        of DART types and of classes derived from them.
        """
        name = expand(re.sub(r"\s+", "", name).lstrip(":"), namespace_aliases)
        scope = tokens.scopes.get(index, ())
        found = api.find(name, scope, imports, tokens.aliases)
        if found[0]:
            return found
        for size in range(len(scope), 0, -1):
            enclosing = "::".join(scope[:size])
            for parent in ancestry.get(enclosing, ()):
                if f"{parent}::{name}" in tokens.aliases:
                    return tokens.aliases[f"{parent}::{name}"], f"{parent}::{name}"
            for base in sorted(local_bases.get(enclosing, ())):
                found = api.find(name, tuple(base.split("::")), imports, tokens.aliases)
                if found[0]:
                    return found
        head, _, nested = name.rpartition("::")
        if head:
            outer = lookup(head, tokens, index, imports, namespace_aliases)[0]
            owners = (
                [api.owner(outer), *sorted(api.ancestors(outer))]
                if outer
                else sorted(local_bases.get(head, ()))
            )
            for owner in owners:
                if f"{owner}::{nested}" in api.types:
                    return f"{owner}::{nested}", None
        return None, None

    def resolve(name, tokens, index, imports, namespace_aliases):
        return lookup(name, tokens, index, imports, namespace_aliases)[0]

    def wrapped(name, tokens, index, imports, namespace_aliases):
        """Whether `name` resolves through a source alias that wraps its type."""
        alias = lookup(name, tokens, index, imports, namespace_aliases)[1]
        return alias in tokens.wrapped

    def pointer_alias(name, tokens, index, imports, namespace_aliases):
        resolved, alias = lookup(name, tokens, index, imports, namespace_aliases)
        return (
            alias in tokens.raw_pointers
            if alias
            else (resolved in api.raw_pointers or resolved in api.standard_pointers)
        )

    # Member fields are shared across headers and implementation files.
    for _ in range(3):
        for (
            path,
            tokens,
            classes,
            _,
            source_aliases,
            imports,
            namespace_aliases,
        ) in files:
            visible(path, tokens)
            for name, values, index in source_aliases:
                for start, _, value in names_in(values):
                    resolved = resolve(value, tokens, index, imports, namespace_aliases)
                    if resolved:
                        wrapper = wraps(
                            values,
                            lambda value: resolve(
                                value, tokens, index, imports, namespace_aliases
                            )
                            and not wrapped(
                                value, tokens, index, imports, namespace_aliases
                            ),
                        )
                        pointer = (
                            raw_pointer(values)
                            or any(
                                target
                                in {
                                    "std::shared_ptr",
                                    "std::unique_ptr",
                                    "std::weak_ptr",
                                }
                                and not in_template_argument(values, offset)
                                for offset, _, target in names_in(values)
                            )
                            or not in_template_argument(values, start)
                            and pointer_alias(
                                value, tokens, index, imports, namespace_aliases
                            )
                        )
                        targets[path][name] = (resolved, wrapper, pointer)
                        publish(tokens, name, resolved, wrapper, pointer)
                        break
            for cls in classes:
                bases = set()
                for raw in cls["bases"]:
                    raw = base_name(raw)
                    resolved = resolve(
                        raw, tokens, cls["index"], imports, namespace_aliases
                    )
                    if resolved:
                        bases.update(api.ancestors(resolved))
                    bases.update(local_bases.get(raw, set()))
                if bases:
                    local_bases[cls["name"]] = bases
                    local_bases[cls["name"].split("::")[-1]] = bases
    for path, tokens, *_ in files:
        visible(path, tokens)

    source_types = {
        name
        for _, _, classes, _, source_aliases, _, _ in files
        for name in [
            *(cls["name"] for cls in classes),
            *(alias[0] for alias in source_aliases),
        ]
    }
    source_types.update(name.split("::")[-1] for name in tuple(source_types))
    for path, tokens, classes, functions, _, imports, namespace_aliases in files:
        values = tokens.values
        tokens.source_relevant = path.startswith("dartsim/")
        declaration_indices = {function["name_index"] for function in functions}
        heads = [(cls["index"], cls["body"]) for cls in classes]
        for start, end, name in names_in(values):
            resolved = resolve(name, tokens, start, imports, namespace_aliases)
            type_end = end
            while not resolved and "::" in name:
                name = name.rsplit("::", 1)[0]
                type_end -= 2
                resolved = resolve(name, tokens, start, imports, namespace_aliases)
            if not resolved:
                continue
            templates = sorted(
                {
                    declaration
                    for owner in api.ancestors(resolved) | {resolved}
                    for declaration in api.type_templates.get(owner, ())
                }
            )
            final_classes = sorted(
                owner
                for owner in api.ancestors(resolved) | {resolved}
                if api.classes.get(owner, {}).get("final")
            )
            enums = sorted(
                {
                    declaration
                    for owner in api.ancestors(resolved) | {resolved}
                    for declaration in api.type_enums.get(owner, ())
                }
            )
            add(
                "types",
                resolved,
                path,
                tokens.line(start),
                **({"template_declarations": templates} if templates else {}),
                **({"final_classes": final_classes} if final_classes else {}),
                **({"enum_declarations": enums} if enums else {}),
            )
            tokens.source_relevant = True
            referenced.update(api.ancestors(resolved))
            constructed = api.constructible(resolved)
            if (
                constructed
                and not wrapped(name, tokens, start, imports, namespace_aliases)
                and constructs(tokens, start, type_end, declaration_indices, heads)
            ):
                row = add(
                    "constructors",
                    resolved,
                    path,
                    tokens.line(start),
                    declarations=[],
                )
                row["declarations"].extend(
                    public_declaration(d)
                    for d in api.constructor_declarations(constructed)
                )
                after = template_end(values, type_end)
                variable = variable_after_type(values, type_end)
                if variable is not None:
                    after = array_end(tokens, variable + 1)
                if (
                    constructed not in api.declares_constructor
                    and api.brace_fields.get(constructed)
                    and not any(head < start < body for head, body in heads)
                    and (
                        values[after : after + 1] == ["{"]
                        or values[after : after + 2] == ["=", "{"]
                    )
                ):
                    row["brace_member_declarations"] = [
                        {"name": member["name"], **public_declaration(member)}
                        for member in api.brace_fields[constructed]
                    ]
            j = (
                None
                if in_template_argument(values, start)
                else variable_after_type(values, type_end)
            )
            if j is not None:
                owner = api.owner(resolved)
                if owner:
                    types = {resolved}
                    if "*" in values[
                        template_end(values, type_end) : j
                    ] or pointer_alias(name, tokens, start, imports, namespace_aliases):
                        types.add(RAW_POINTER)
                    dimension = j + 1
                    while (
                        values[dimension : dimension + 1] == ["["]
                        and dimension in tokens.pairs
                    ):
                        types = {"__element__:" + value for value in types}
                        dimension = tokens.pairs[dimension] + 1
                    bind_variable(tokens, j, types)
                    if is_field(tokens, j, classes):
                        fields[values[j]].update(types)
        for start, end, name in names_in(values):
            if resolve(name, tokens, start, imports, namespace_aliases):
                continue
            if (
                ("::" in name and not name.startswith("dart::"))
                or THIRD_PARTY.match(name)
                or name.split("::")[-1] in source_types
                or name in {"int", "double", "float", "bool", "char", "size_t"}
            ):
                j = variable_after_type(values, end)
                if j is None:
                    continue
                contained = set(local_bases.get(name, ()))
                source_owner = source_class(
                    name, tokens.scopes.get(start, ()), imports, namespace_aliases
                )
                if source_owner:
                    contained.update(local_bases.get(source_owner, ()))
                if name in {"std::shared_ptr", "std::unique_ptr", "std::weak_ptr"}:
                    for offset, _, value in names_in(values[end:j]):
                        resolved = resolve(
                            value, tokens, end + offset, imports, namespace_aliases
                        )
                        if api.owner(resolved):
                            contained.add(resolved)
                    if contained:
                        contained.add(RAW_POINTER)
                if not contained:
                    contained.update(
                        container_elements(
                            first_template_argument(values, end),
                            api,
                            lambda value: resolve(
                                value, tokens, start, imports, namespace_aliases
                            ),
                            lambda value: pointer_alias(
                                value, tokens, start, imports, namespace_aliases
                            ),
                        )
                    )
                contained = contained or {"__non_dart__"}
                if source_owner:
                    contained.add(SOURCE_CLASS + source_owner)
                bind_variable(tokens, j, contained)
                if is_field(tokens, j, classes):
                    fields[values[j]].update(contained)

    relevant_files = {path for path, tokens, *_ in files if tokens.source_relevant}
    for path, tokens, *_ in files:
        tokens.source_relevant = any(
            header in relevant_files for header in closure[path]
        )

    def candidates(name, receiver_types, operator=None, table=api.members):
        # shortcut: lexical matching retains overload candidates, use compiler analysis for exact selection.
        if name in {"operator->", "operator[]", "operator()"}:
            receiver_types = receiver_types - api.standard_pointers
            if not receiver_types or RAW_POINTER in receiver_types:
                return []
        if operator == ".":
            receiver_types = receiver_types - api.standard_pointers
            if not receiver_types:
                return []
        owners = (
            set().union(*(api.ancestors(t) for t in receiver_types))
            if receiver_types
            else referenced
        )
        if operator == "." and name in {"get", "lock"}:
            owners = {api.owner(t) for t in receiver_types}
        return [d for d in table.get(name, []) if d["class"] in owners]

    def enclosing_bases(tokens, index):
        """The DART bases of the classes around `index`, which `this` reaches."""
        scope = tokens.scopes.get(index, ())
        return set().union(
            *(
                local_bases.get("::".join(scope[:size]), ())
                for size in range(1, len(scope) + 1)
            )
        )

    def source_member_bases(
        owner, name, tokens, index, imports, namespace_aliases, depth=0
    ):
        """DART bases visible after source members and class using-declarations."""
        if depth > 8:
            return set()
        for cls in [owner, *ancestry.get(owner, ())]:
            brought = set()
            for short, target, where, *_ in tokens.using:
                if short == name and where == tuple(cls.split("::")):
                    spelling = target.rpartition("::")[0]
                    base = api.resolve(
                        expand(spelling, namespace_aliases),
                        where,
                        imports,
                        tokens.aliases,
                    )
                    brought.update(api.ancestors(base))
                    parent = source_class(spelling, where, imports, namespace_aliases)
                    if parent:
                        brought.update(
                            source_member_bases(
                                parent,
                                name,
                                tokens,
                                index,
                                imports,
                                namespace_aliases,
                                depth + 1,
                            )
                        )
            if (cls, name) in source_returns or brought:
                return brought
        return set(local_bases.get(owner, ()))

    def source_member_types(types, name, tokens, index, imports, namespace_aliases):
        result = set(types)
        for marker in types:
            if marker.startswith(SOURCE_CLASS):
                owner = marker.removeprefix(SOURCE_CLASS)
                result.difference_update(local_bases.get(owner, ()))
                result.update(
                    source_member_bases(
                        owner, name, tokens, index, imports, namespace_aliases
                    )
                )
        return result

    def record(section, name, declarations, inferred, path, index, tokens):
        if not declarations:
            return
        row = add(
            section,
            name,
            path,
            tokens.line(index),
            declarations=[],
            receiver_types=set(),
            unresolved_count=0,
        )
        row["declarations"].extend(public_declaration(d) for d in declarations)
        dart_receivers = {t for t in inferred if t.startswith("dart::")}
        row["receiver_types"].update(dart_receivers)
        row["unresolved_count"] += not bool(dart_receivers)

    def free_function(name, tokens, index, path, imports, namespace_aliases):
        """The DART functions that an unqualified call can reach.

        Lookup stops at the innermost scope that declares the name: a function
        of an enclosing namespace or class, or a using-declaration, counts in
        its own scope, and a using-directive of a DART namespace at the global
        scope.
        """
        scope = tokens.scopes.get(index, ())
        found = defaultdict(list)  # depth -> the DART functions declared there
        declared_at = set()
        for size in range(len(scope), 0, -1):
            if "::".join(scope[:size] + (name,)) in api.free_functions:
                found[size].append("::".join(scope[:size] + (name,)))
        for short, target, where, start, stop, depth in tokens.using:
            if start < index < stop and scope[: len(where)] == where:
                if short is None:
                    target = qualified_function(
                        target + "::" + name, where, tokens, index, namespace_aliases
                    )
                    found[0] += [target] if target else []
                    continue
                if short != name:
                    continue
                declared_at.add(depth)
                target = qualified_function(
                    target, where, tokens, index, namespace_aliases
                )
                found[depth] += [target] if target else []
        for header in closure[path]:
            for owner in declared[header].get(name, ()):
                if scope[: len(owner)] == owner:
                    declared_at.add(len(owner))
        depths = declared_at | {depth for depth, items in found.items() if items}
        result = set(found[max(depths, default=0)])
        if any("::".join(scope[:size]) in source_classes for size in declared_at):
            return sorted(result)  # member lookup suppresses ADL
        opening = template_end(tokens.values, index + 1)
        closing = tokens.pairs.get(opening)
        if closing is not None:
            start = i = opening + 1
            while i <= closing:
                if i == closing or tokens.values[i] == ",":
                    types = receiver(tokens, i - 1, imports, namespace_aliases)
                    for offset, _, argument in names_in(tokens.values[start:i]):
                        resolved = resolve(
                            argument, tokens, start + offset, imports, namespace_aliases
                        )
                        if resolved:
                            types.add(resolved)
                    for owner in set().union(*(api.ancestors(t) for t in types)):
                        namespace = owner.rpartition("::")[0]
                        while namespace in api.classes:
                            namespace = namespace.rpartition("::")[0]
                        candidate = namespace + "::" + name
                        if candidate in api.free_functions:
                            result.add(candidate)
                    start = i + 1
                elif tokens.values[i] in {"(", "[", "{"} and i in tokens.pairs:
                    i = tokens.pairs[i]
                i += 1
        return sorted(result)

    def qualified_function(name, scope, tokens, index, namespace_aliases):
        here = tokens.scopes.get(index, ())
        imports = [
            expand(target.lstrip(":"), namespace_aliases)
            for short, target, where, start, stop, _ in tokens.using
            if short is None and start < index < stop and here[: len(where)] == where
        ]
        if "dart" in imports:
            imports += ["dart::" + space for space in imports if space != "dart"]
        for candidate in api.spellings(expand(name, namespace_aliases), scope, imports):
            if candidate in api.free_functions:
                return candidate
        return None

    def returns(declarations):
        result = set()
        for item in declarations:
            return_tokens = item.get("return_tokens", ())
            scope = (
                tuple(item["class"].split("::"))
                if item["class"]
                else tuple(item["name"].split("::")[:-1])
            )
            sequence = next(
                (
                    end
                    for start, end, value in names_in(return_tokens)
                    if value
                    in {
                        "std::vector",
                        "std::array",
                        "std::deque",
                        "std::list",
                        "std::forward_list",
                    }
                    and not in_template_argument(return_tokens, start)
                ),
                None,
            )
            if sequence is not None:
                contained = container_elements(
                    first_template_argument(return_tokens, sequence),
                    api,
                    lambda value: api.resolve(value, scope),
                )
                result.update(contained or {"__non_dart__"})
                continue
            for _, _, value in names_in(return_tokens):
                resolved = api.resolve(value, scope)
                owner = api.owner(resolved)
                if owner:
                    result.add(resolved)
                    if raw_pointer(return_tokens) or resolved in (
                        api.raw_pointers | api.standard_pointers
                    ):
                        result.add(RAW_POINTER)
        return result

    def arrow_types(types):
        return returns(candidates("operator->", types)) or types

    def receiver(tokens, before, imports, namespace_aliases, depth=0):
        if before < 0 or depth > 8:
            return set()
        values = tokens.values
        value = values[before]
        if value == ")" and before in tokens.pairs:
            opening = tokens.pairs[before]
            function = opening - 1
            if function >= 0 and values[function] == ">":
                angle = 1
                function -= 1
                while function >= 0 and angle:
                    angle += (values[function] == ">") - (values[function] == "<")
                    function -= 1
            if function >= 0:
                method = values[function]
                if function > 0 and values[function - 1] in {"->", "."}:
                    types = receiver(
                        tokens, function - 2, imports, namespace_aliases, depth + 1
                    )
                    if values[function - 1] == "->":
                        types = arrow_types(types)
                    if method == "get" and types & api.standard_pointers:
                        return {api.owner(t) for t in types if api.owner(t)} | {
                            RAW_POINTER
                        }
                    if method in {"at", "back", "front"} and elements(types):
                        return elements(types)
                    types = source_member_types(
                        types, method, tokens, function, imports, namespace_aliases
                    )
                    declarations = candidates(method, types, values[function - 1])
                    if not declarations:
                        explicit = values[function + 1 : opening]
                        if "std" in explicit and "vector" in explicit:
                            return {"__non_dart__"}
                        source_declarations = []
                        for marker in types:
                            if not marker.startswith(SOURCE_CLASS):
                                continue
                            owner = marker.removeprefix(SOURCE_CLASS)
                            for owner in [owner, *ancestry.get(owner, ())]:
                                declarations = source_returns.get((owner, method), ())
                                if declarations:
                                    source_declarations.extend(declarations)
                                    break
                        source_types = returns(source_declarations)
                        if source_types:
                            return source_types
                        if "__non_dart__" in types:
                            return {"__non_dart__"}
                    return returns(declarations)
                if function > 0 and values[function - 1] == "::":
                    qualifier = "::".join(qualifier_path(values, function))
                    resolved = resolve(
                        qualifier,
                        tokens,
                        function,
                        imports,
                        namespace_aliases,
                    )
                    if resolved:
                        return returns(candidates(method, {resolved}))
                    free = qualified_function(
                        qualifier + "::" + method,
                        tokens.scopes.get(function, ()),
                        tokens,
                        function,
                        namespace_aliases,
                    )
                    if free:
                        return returns(api.free_functions[free])
                if method in {"dynamic_cast", "static_cast"}:
                    for _, _, value in names_in(values[function + 1 : opening]):
                        resolved = resolve(
                            value, tokens, function, imports, namespace_aliases
                        )
                        if api.owner(resolved):
                            types = {resolved}
                            if "*" in values[function + 1 : opening]:
                                types.add(RAW_POINTER)
                            return types
                        if value in local_bases:
                            return set(local_bases[value])
                types = receiver(
                    tokens, function, imports, namespace_aliases, depth + 1
                )
                result = returns(candidates("operator()", types))
                if result:
                    return result
        if value == "]" and before in tokens.pairs:
            types = receiver(
                tokens, tokens.pairs[before] - 1, imports, namespace_aliases, depth + 1
            )
            return (
                returns(candidates("operator[]", types))
                or elements(types)
                or (types - {RAW_POINTER})
            )
        if before > 1 and values[before - 1] in {"->", "."}:
            owner = receiver(tokens, before - 2, imports, namespace_aliases, depth + 1)
            if values[before - 1] == "->":
                owner = arrow_types(owner)
            declarations = candidates(
                value, owner, values[before - 1], api.data_members
            )
            types = returns(declarations)
            if types:
                return types
        types = variable_types(tokens, before, fields)
        if not types and before > 1 and values[before - 1] in {"->", "."}:
            if "__non_dart__" in owner:  # an unknown field of a non-DART object
                return {"__non_dart__"}
        return types

    # Propagate ordinary auto aliases from explicit DART fields and return values.
    for _ in range(3):
        for _, tokens, _, _, _, imports, namespace_aliases in files:
            values = tokens.values
            for i, value in enumerate(values):
                if value != "auto":
                    continue
                j = i + 1
                while j < len(values) and values[j] in {"const", "&", "&&", "*"}:
                    j += 1
                if j + 1 >= len(values) or values[j + 1] != "=":
                    continue
                end = j + 2
                while end < len(values) and values[end] != ";":
                    end += 1
                if end < len(values):
                    inferred = receiver(tokens, end - 1, imports, namespace_aliases)
                    bind_variable(tokens, j, inferred)

    for path, tokens, classes, functions, _, imports, namespace_aliases in files:
        values = tokens.values
        if not tokens.source_relevant:
            tokens.source_relevant = any(
                qualified_function(
                    name, tokens.scopes.get(start, ()), tokens, start, namespace_aliases
                )
                for start, _, name in names_in(values)
            )
        declaration_indices = {function["name_index"] for function in functions}
        class_bodies = {cls["body"] for cls in classes}
        for cls in classes:
            bases = local_bases.get(cls["name"], set())
            for item in cls["members"]:
                signature = member_signature(
                    item,
                    lambda name: api.owner(
                        resolve(name, tokens, item["index"], imports, namespace_aliases)
                    )
                    or resolve(name, tokens, item["index"], imports, namespace_aliases),
                )
                # shortcut: explicit virtuals retain candidates, use compiler analysis to resolve full signatures.
                declarations = [
                    d
                    for d in api.members.get(item["name"], [])
                    if d["class"] in bases
                    and d["virtual"]
                    and (
                        item["override"]
                        or item["virtual"]
                        or signature is not None
                        and signature
                        == member_signature(
                            d,
                            lambda name: api.owner(
                                api.resolve(name, tuple(d["class"].split("::")))
                            )
                            or api.resolve(name, tuple(d["class"].split("::"))),
                        )
                    )
                ]
                if declarations:
                    row = add(
                        "overrides",
                        cls["name"] + "::" + item["name"],
                        path,
                        tokens.line(item["index"]),
                        base_classes=sorted(bases),
                        signatures=set(),
                        declarations=[],
                    )
                    row["signatures"].add(item["signature"])
                    row["declarations"].extend(
                        public_declaration(d) for d in declarations
                    )
        for i, name in enumerate(values):
            syntax_operator = {
                "->": "operator->",
                "[": "operator[]",
                "(": "operator()",
            }.get(name)
            if syntax_operator and not any(
                b[2] == i - 1 for b in tokens.bindings
            ):  # declaration initializers are constructions, not operator calls
                inferred = receiver(tokens, i - 1, imports, namespace_aliases)
                record(
                    "members",
                    syntax_operator,
                    candidates(syntax_operator, inferred),
                    inferred,
                    path,
                    i,
                    tokens,
                )
            if name.startswith("DART_"):
                start = tokens.text.rfind("\n", 0, tokens.offsets[i]) + 1
                prefix = tokens.text[start : tokens.offsets[i]]
                if not re.fullmatch(r"\s*#\s*define\s+", prefix):
                    add(
                        "macros",
                        name,
                        path,
                        tokens.line(i),
                        declared_in_dart=name in api.macros,
                        defined_in_source=name in source_macros,
                    )
            if i in declaration_indices or not IDENTIFIER.match(name):
                continue
            j = template_end(values, i + 1)
            call = j < len(values) and values[j] == "("
            access = values[i - 1] if i and values[i - 1] in {".", "->"} else None
            qualifier = None
            if i and values[i - 1] == "::":
                qualifier = "::".join(qualifier_path(values, i))
                resolved = resolve(qualifier, tokens, i, imports, namespace_aliases)
            if not call:
                if qualifier is not None:
                    begin = i - len(TOKEN.findall(qualifier)) - 1
                    free = (
                        None
                        if "using" in values[max(0, begin - 2) : begin]
                        else qualified_function(
                            qualifier + "::" + name,
                            tokens.scopes.get(i, ()),
                            tokens,
                            i,
                            namespace_aliases,
                        )
                    )
                    if free:
                        add("free_functions", free, path, tokens.line(i))
                    for candidate in api.spellings(
                        expand(qualifier + "::" + name, namespace_aliases),
                        tokens.scopes.get(i, ()),
                        imports,
                    ):
                        if candidate in api.variables:
                            add(
                                "variables",
                                candidate,
                                path,
                                tokens.line(i),
                                declarations=[
                                    public_declaration(d)
                                    for d in api.variables[candidate]
                                ],
                            )
                            break
                if access and tokens.source_relevant:
                    inferred = receiver(tokens, i - 2, imports, namespace_aliases)
                    if access == "->":
                        inferred = arrow_types(inferred)
                    declarations = candidates(
                        name, inferred, access if inferred else None, api.data_members
                    )
                    record(
                        "data_members", name, declarations, inferred, path, i, tokens
                    )
                elif qualifier is not None and resolved:
                    declarations = candidates(name, {resolved}, table=api.data_members)
                    record(
                        "data_members", name, declarations, {resolved}, path, i, tokens
                    )
                elif (
                    access is None
                    and qualifier is None
                    and name in api.data_members
                    and tokens.source_relevant
                    and tokens.enclosing[i] not in class_bodies
                    and not any(  # a local declaration that every build sees here
                        b[3] == name
                        and b[0] <= i <= b[1]
                        and b[2] <= i
                        and set(tokens.branches[b[2]]) <= set(tokens.branches[i])
                        for b in tokens.bindings
                    )
                ):
                    inferred = enclosing_bases(tokens, i)  # the implicit `this`
                    if inferred:
                        declarations = candidates(
                            name, inferred, table=api.data_members
                        )
                        record(
                            "data_members",
                            name,
                            declarations,
                            inferred,
                            path,
                            i,
                            tokens,
                        )
                continue
            declarations = []
            inferred = set()
            if access:
                if not tokens.source_relevant:
                    continue
                inferred = receiver(tokens, i - 2, imports, namespace_aliases)
                if access == "->":
                    inferred = arrow_types(inferred)
                inferred = source_member_types(
                    inferred, name, tokens, i, imports, namespace_aliases
                )
                declarations = candidates(name, inferred, access if inferred else None)
            elif qualifier is not None:
                if resolved:
                    inferred = {resolved}
                    declarations = candidates(name, inferred)
                else:
                    owner = source_class(
                        qualifier, tokens.scopes.get(i, ()), imports, namespace_aliases
                    )
                    bases = (
                        source_member_bases(
                            owner, name, tokens, i, imports, namespace_aliases
                        )
                        if owner
                        else set()
                    )
                    if bases:
                        inferred = bases
                        declarations = candidates(name, inferred)
                    free = qualified_function(
                        qualifier + "::" + name,
                        tokens.scopes.get(i, ()),
                        tokens,
                        i,
                        namespace_aliases,
                    )
                    if free:
                        add("free_functions", free, path, tokens.line(i))
            else:
                inferred = enclosing_bases(tokens, i)
                scope = tokens.scopes.get(i, ())
                for size in range(len(scope), 0, -1):
                    owner = "::".join(scope[:size])
                    if owner in source_classes:
                        inferred = source_member_bases(
                            owner, name, tokens, i, imports, namespace_aliases
                        )
                        break
                if inferred:
                    declarations = candidates(name, inferred)
                if not declarations:
                    for free in free_function(
                        name, tokens, i, path, imports, namespace_aliases
                    ):
                        add("free_functions", free, path, tokens.line(i))
            if j == i + 1:
                declarations = [
                    d
                    for d in declarations
                    if not (name == "get" and d["signature"].startswith("template"))
                ]
            record("members", name, declarations, inferred, path, i, tokens)

    result = {}
    for section, table in tables.items():
        result[section] = []
        for name in sorted(table):
            row = table[name]
            row["examples"] = sorted(row["examples"])[:3]
            for key in ("receiver_types", "signatures"):
                if key in row:
                    row[key] = sorted(row[key])
            if "declarations" in row:
                row["declarations"] = sorted(
                    {
                        json.dumps(d, sort_keys=True): d for d in row["declarations"]
                    }.values(),
                    key=lambda d: (d["class"], d["signature"]),
                )
            if section == "members":
                row["classification"] = classify_member(name, row["declarations"])
            result[section].append(row)
    return result


def revision(checkout):
    checkout = Path(checkout)
    sha = subprocess.check_output(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True
    ).strip()
    status = subprocess.check_output(
        ["git", "-C", str(checkout), "status", "--porcelain", "--untracked-files=all"],
        text=True,
    )
    if status:
        raise ValueError("source checkout has local changes; scan a clean revision")
    return sha


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "checkout", type=Path, nargs="?", help="clean gz-physics checkout"
    )
    parser.add_argument("--gz-sim", type=Path, help="clean gz-sim checkout")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    args = parser.parse_args(argv)
    if args.checkout is None:
        print("SKIPPED: no gz-physics checkout supplied; inventory was not checked.")
        return 0
    try:
        recorded = json.loads(args.output.read_text()) if args.output.exists() else None
        if args.check and recorded is None:
            raise ValueError("no recorded inventory to check")
        api = index_api(ROOT / "dart")
        sources = {}
        for name, checkout in (("gz-physics", args.checkout), ("gz-sim", args.gz_sim)):
            if checkout is not None:
                sources[name] = {
                    "sha": revision(checkout),
                    **scan_sources(api, checkout),
                }
            elif recorded and name in recorded["sources"]:
                sources[name] = recorded["sources"][name]
                print(
                    f"SKIPPED: {name} was not rescanned; retaining its recorded inventory."
                )
            else:
                raise ValueError(
                    "initial generation requires --gz-sim to record its revision and direct DART use"
                )
        generated = {"schema_version": 1, "sources": sources}
        output = json.dumps(generated, indent=2, sort_keys=True) + "\n"
        if args.check:
            expected = args.output.read_text()
            if output != expected:
                print(
                    "FAILED: DART API inventory differs from the recorded declarations, uses or revisions."
                )
                print(
                    "".join(
                        difflib.unified_diff(
                            expected.splitlines(True),
                            output.splitlines(True),
                            fromfile="recorded",
                            tofile="regenerated",
                        )
                    ),
                    end="",
                )
                return 1
            print(
                "PASS: DART API inventory matches the recorded revision and declarations."
            )
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(output)
            print("Wrote DART API inventory.")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"FAILED: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
